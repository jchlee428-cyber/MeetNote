export function buildUserPrompt(
  transcript: string,
  meta?: { title?: string; location?: string; attendees?: string }
): string {
  return `[회의 추가 정보]
회의 제목: ${meta?.title || "미지정"}
회의 장소: ${meta?.location || "미지정"}
참석자: ${meta?.attendees || "미지정"}

[음성 전사 텍스트 원문]
${transcript}

위 음성 전사 내용을 바탕으로 지침에 맞추어 JSON 회의록을 생성하십시오.`;
}
